function render(region, kind, regionByFullName, servicePath, esc) {
  if (kind !== 'taksong') return '';
  if (region.full_name === '강원특별자치도') {
    const links = Array.from(pickupNotes.keys(), name => {
      const city = regionByFullName.get(name);
      const label = city.name.replace(/[시군]$/, '') + '탁송';
      return '<li><a href="' + esc(servicePath(city, kind)) + '">' + esc(label) + '</a></li>';
    });
    return '<section><h2>강원도탁송 지역별 차량 인수·인계 안내</h2><p>차를 맡길 시·군을 선택하면 해당 지역의 차량 인계 방법과 예상요금 조회를 확인할 수 있습니다.</p><ul>' + links.join('') + '</ul></section>';
  }
  const note = pickupNotes.get(region.full_name);
  if (!note) return '';
  return '<section><h2>' + esc(region.name.replace(/[시군]$/, '')) + '탁송 차량 인계 방법</h2><p>' + esc(note) + '</p><a href="' + esc(servicePath(regionByFullName.get('강원특별자치도'), kind)) + '">강원도탁송 지역별 안내</a></section>';
}

module.exports = { render };
