'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..'),read=p=>fs.readFileSync(path.join(root,p),'utf8');
const seo=read('tools/audit_live_seo.py'),server=read('server.js'),home=read('index.html');
const slugs=['seoul','busan','incheon','daegu','gwangju','daejeon','ulsan','sejong','gyeonggi','gangwon','chungbuk','chungnam','jeonbuk','jeonnam','gyeongbuk','gyeongnam','jeju'];
const batch2=[...slugs.map(s=>'/daeri/'+s+'/'),'/service/corporate/','/service/golf/','/service/daily-driver/'];
const batch1=[...slugs.map(s=>'/taksong/'+s+'/'),'/reviews/history/','/fare/','/coverage/'];
assert.equal(batch2.length,20);
assert.equal(new Set(batch2).size,20);
assert.equal(batch2.filter(s=>batch1.includes(s)).length,0,'Second batch must not overlap first');
assert(seo.includes('NATIONWIDE_DAERI_BATCH_20'),'Live audit needs second batch targets');
for(const url of batch2)assert(seo.includes('"'+url+'"'),'Missing monitored SEO route '+url);
assert(server.includes('nationwideCoveragePage()'),'National page exists');
assert(server.includes('&amp;kind=daeri">확인된 완료기록'),'National directory links to service-specific verified rides');
assert(server.includes('/fare/?service=daeri&amp;from='),'National directory links to prefilled driver fare');
assert(server.includes('matchingHistoryRegion(x,matchedRegion,regions)'),'No fabricated regional ride matching');
assert(server.includes('historicalRides.length!==2591'),'Original ride archive retained');
assert(home.includes('href="/coverage/"'),'Homepage links to nationwide hub');
console.log('PASS: second 20 nationwide driver-service routes and truthful region-to-ride-to-fare navigation');
