'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const ROOT=path.join(__dirname,'..');
const html=fs.readFileSync(path.join(ROOT,'index.html'),'utf8');
const server=fs.readFileSync(path.join(ROOT,'server.js'),'utf8');
const config=JSON.parse(fs.readFileSync(path.join(ROOT,'data/seo-pages.json'),'utf8'));
const name='스마트24 전국대리운전';
const url='https://jeongukdaeri.kr/';
const title=config.pages.find(x=>x.path==='/')?.title;
assert(title,'homepage SEO title exists');
assert(html.includes('<title>'+title+'</title>'),'homepage title and SEO config agree');
assert(title.endsWith(' | '+name),'homepage title exposes preferred Korean site name');
assert(html.includes('<meta name="application-name" content="'+name+'">'),'app name');
assert(html.includes('<meta property="og:site_name" content="'+name+'">'),'home OG site name');
assert(html.includes('<header><strong>'+name+'</strong>'),'visible top header brand');
assert(html.includes('<link rel="canonical" href="'+url+'">'),'homepage canonical preserved');
const nodes=[...html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)].map(m=>JSON.parse(m[1]));
const websites=nodes.filter(x=>x['@type']==='WebSite');
assert.equal(websites.length,1,'exactly one WebSite node for root');
assert.equal(websites[0].name,name,'preferred Korean WebSite.name');
assert.equal(websites[0].url,url,'site homepage URL');
assert(websites[0].alternateName.includes('스마트24'),'short brand alternate');
assert(websites[0].alternateName.includes('스마트24 전국대리운전·24시탁송'),'old full site name preserved as alternative');
assert(server.includes("SITE_NAME='"+name+"'"),'dynamic pages share same site name');
assert(server.includes('<meta property="og:site_name" content="${SITE_NAME}">'),'dynamic pages OG site name');
assert((server.match(/name:SITE_NAME,url:/g)||[]).length>=2,'nested WebSite links consistently identify site');
assert(html.includes('href="tel:18114294"'),'homepage phone unchanged');
assert(html.includes('href="/fare/"')||html.includes('href="/fare/?'),'fare links retained');
console.log('PASS Korean homepage site identity, WebSite/OG/app meta and dynamic site-name references');
