-- Install only after checking existing production table and taking a backup.
create table if not exists public.site_admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);
alter table public.site_admins enable row level security;
drop policy if exists "admins can read own membership" on public.site_admins;
create policy "admins can read own membership" on public.site_admins
  for select to authenticated using (user_id=auth.uid());

-- Dedicated import table. Only verified, privacy-screened completed trips are inserted.
create table if not exists public.ride_history (
  id bigint generated by default as identity primary key,
  ride_date date not null,
  departure_time time without time zone not null,
  departure text not null,
  destination text not null,
  fare bigint not null check (fare>0),
  created_at timestamptz not null default now(),
  unique(ride_date,departure_time,departure,destination,fare)
);
alter table public.ride_history enable row level security;
drop policy if exists "public read completed rides" on public.ride_history;
create policy "public read completed rides" on public.ride_history
  for select to anon,authenticated using (true);
drop policy if exists "site admins insert verified rides" on public.ride_history;
create policy "site admins insert verified rides" on public.ride_history
  for insert to authenticated
  with check (exists (select 1 from public.site_admins where user_id=auth.uid()));
